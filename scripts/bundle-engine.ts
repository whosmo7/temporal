// Bundles src/api/edge.ts (runTurn, the engine it imports, and the demo world) into one ES module
// the commit-turn and seed-demo Edge Functions can import. Deno can't resolve the engine's extensionless imports, and keeping a second
// copy of the rules is not an option (inheritance-backend), so the function gets this build.
// Run by `npm run functions:deploy`; the output is gitignored.

import { build } from 'esbuild';

await build({
  entryPoints: ['src/api/edge.ts'],
  outfile: 'supabase/functions/_shared/engine.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  banner: { js: '// Generated by scripts/bundle-engine.ts from src/engine. Do not edit.' },
  logLevel: 'info',
});

// The LLM playthrough simulator for the admin panel's llm-simulate function (decision 040). The
// Gemini SDK stays an import, resolved by that function's deno.json to npm:@google/genai.
await build({
  entryPoints: ['scripts/llm/edge.ts'],
  outfile: 'supabase/functions/_shared/sim.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['@google/genai'],
  banner: { js: '// Generated by scripts/bundle-engine.ts from scripts/llm. Do not edit.' },
  logLevel: 'info',
});
